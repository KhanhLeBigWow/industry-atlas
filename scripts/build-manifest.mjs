/* Industry Atlas - manifest generator.
 * Run: node scripts/build-manifest.mjs   (run BEFORE every deploy, after
 * adding or editing industry modules; validate-modules.mjs first).
 * Loads every module in a window shim and emits assets/data/manifest.js:
 * a ~25KB summary (status, marketSize incl mapValue, geography roles) that
 * lets every page except industry.html/library.html skip loading the full
 * 300-line modules. industry.html loads only its own module dynamically. */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const win = {};
global.window = win;

async function load(rel) {
  const src = await readFile(join(ROOT, rel), "utf8");
  new Function("window", src)(win);
}

await load("assets/data/taxonomy.js");
win.ATLAS_INDUSTRIES = {};
const modDir = join(ROOT, "assets", "data", "industries");
const files = (await readdir(modDir)).filter((f) => f.endsWith(".js"));
for (const f of files) await load("assets/data/industries/" + f);

const industries = {};
for (const [id, m] of Object.entries(win.ATLAS_INDUSTRIES)) {
  industries[id] = {
    status: (m.meta && m.meta.status) || "profile",
    marketSize: m.meta ? m.meta.marketSize : null,
    geo: (m.geography || []).map((g) => ({ country: g.country, role: g.role })),
  };
}

const stamp = new Date().toISOString().slice(0, 10);
const out =
  "/* GENERATED by scripts/build-manifest.mjs on " + stamp + " - do not edit by hand.\n" +
  " * Summary of every industry module so most pages can skip loading them. */\n" +
  "window.ATLAS_MANIFEST = " + JSON.stringify({ generated: stamp, industries }, null, 0) + ";\n";
await writeFile(join(ROOT, "assets", "data", "manifest.js"), out);
console.log("manifest: " + Object.keys(industries).length + " industries, " + Math.round(out.length / 1024) + "KB");
